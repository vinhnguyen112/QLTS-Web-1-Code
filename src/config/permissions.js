// Phân quyền theo 3 nhóm vai trò: Vận hành, Lãnh đạo, Kỹ thuật
const ROLE_GROUPS = {
  OPERATORS: ["SYS_ADMIN", "ASSET_MANAGER"],
  LEADERS: ["SYS_ADMIN", "DIRECTOR", "CHIEF_ACCOUNTANT", "ASSET_ACCOUNTANT", "DEPT_HEAD", "ASSET_MANAGER"],
  TECHNICIANS: ["SYS_ADMIN", "ASSET_MANAGER", "TECHNICIAN", "DIRECTOR"],
};

const PERMISSIONS = {
  MANAGE_SYSTEM: ["SYS_ADMIN"],
  MANAGE_MASTER_DATA: ROLE_GROUPS.OPERATORS,
  MANAGE_ASSETS: ROLE_GROUPS.OPERATORS,
  APPROVE_REQUESTS: ROLE_GROUPS.LEADERS,
  VIEW_DEPRECIATION: ["SYS_ADMIN", "DIRECTOR", "CHIEF_ACCOUNTANT", "ASSET_ACCOUNTANT", "ASSET_MANAGER"],
  VIEW_REPORTS: ["SYS_ADMIN", "DIRECTOR", "CHIEF_ACCOUNTANT", "ASSET_ACCOUNTANT", "ASSET_MANAGER"],
  MANAGE_STOCKTAKES: ["SYS_ADMIN", "ASSET_MANAGER", "DIRECTOR"],
  RESOLVE_MAINTENANCE: ROLE_GROUPS.TECHNICIANS,
  VIEW_AUDIT: ["SYS_ADMIN", "DIRECTOR"],
};

function checkPermission(userRole, permissionKey) {
  if (!userRole) return false;
  if (userRole === "SYS_ADMIN") return true;
  return (PERMISSIONS[permissionKey] || []).includes(userRole);
}

module.exports = {
  ROLE_GROUPS,
  PERMISSIONS,
  checkPermission,
};
